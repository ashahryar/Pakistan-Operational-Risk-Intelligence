# ==========================================================
# COVERAGE GAP -- reported, not silently worked around
# ==========================================================

def test_pdma_earthquake_reports_have_no_parser_and_no_fixtures():
    """
    Documents a real, pre-existing gap rather than hiding it: the
    earthquake_reports raw directories exist but are empty, and no
    parser function for this report type exists anywhere in the repo.
    This test fails loudly (rather than being silently absent) if a
    parser or fixtures are ever added without updating this note.
    """
    for year in ("2025", "2026"):
        pdfs_dir = PDMA_RAW_ROOT / "earthquake_reports" / year / "pdfs"
        if pdfs_dir.exists():
            assert list(pdfs_dir.glob("*.pdf")) == [], (
                f"earthquake PDFs now exist under {pdfs_dir} but Task 8 was "
                f"written when there were none and no parser existed -- "
                f"this suite needs updating, not silently skipping."
            )

    import importlib.util

    assert importlib.util.find_spec("scripts.parsing.parse_earthquake") is None, (
        "an earthquake parser module now exists -- Task 8's fixtures/tests "
        "need to be extended to cover it."
    )
